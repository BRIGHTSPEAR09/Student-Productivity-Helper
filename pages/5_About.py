import streamlit as st

st.title("ℹ️ About This App")

st.markdown("""
### 🎓 Student Productivity Helper

The **Student Productivity Helper** is a web application designed to help students
organize their academic tasks, plan study sessions, and monitor their study
productivity. The goal of this app is to provide a simple platform where students
can manage their school activities and improve their study habits.
""")

st.divider()

# WHAT THE APP DOES
st.header("📌 What the App Does")

st.markdown("""
This application helps students manage their academic responsibilities by
providing tools for task management, study planning, and productivity tracking.

With this app, students can:

- Add and manage their school tasks and assignments
- Plan study sessions for different subjects
- Track how much time they spend studying
- View productivity statistics and study analytics
- Monitor their progress and stay organized

The system acts as a **personal study assistant** that helps students maintain
focus and build consistent study routines.
""")

st.divider()

# TARGET USERS
st.header("👥 Target Users")

st.markdown("""
The Student Productivity Helper is designed for learners who want to improve
their study organization and productivity.

The main users of the application include:

- **High school students**
- **College students**
- **Self learners**
- **Students preparing for exams or projects**

These users can benefit from having a single platform where they can manage
their study tasks and track their productivity.
""")

st.divider()

# INPUTS
st.header("📥 Inputs Collected by the App")

st.markdown("""
The application collects different types of information from the user in order
to generate productivity insights.

Examples of inputs include:

- Tasks and assignments entered by the user
- Study subjects and topics
- Planned study session durations
- Study dates and schedules
- User actions such as marking tasks as completed
""")

st.divider()

# OUTPUTS
st.header("📤 Outputs Displayed by the App")

st.markdown("""
After collecting user inputs, the application processes the data and displays
useful productivity information.

The app provides the following outputs:

- **Task tracking tables** showing tasks and their completion status
- **Study planner sessions** with timers and study duration tracking
- **Productivity dashboard metrics**
- **Study analytics charts and visualizations**

These outputs help users evaluate their study habits and understand their
productivity patterns.
""")

st.divider()

st.info("The Student Productivity Helper aims to support students in developing better study habits, improving time management, and increasing overall academic productivity.")